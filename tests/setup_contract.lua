vim.opt.rtp:prepend(vim.fn.getcwd())
local plugin = require('task_tools')
local options = { tasks = {}, env = { LIFECYCLE = 'value' } }
local caller = vim.deepcopy(options)
plugin.setup(options)
assert(vim.deep_equal(caller, options), 'setup mutated caller configuration')
local commands = vim.api.nvim_get_commands({})
local handlers = vim.api.nvim_get_autocmds({})
assert(not pcall(plugin.setup, false), 'setup(false) must reject an invalid configuration type')
assert(vim.deep_equal(commands, vim.api.nvim_get_commands({})), 'Invalid setup replaced commands')
assert(vim.deep_equal(handlers, vim.api.nvim_get_autocmds({})), 'Invalid setup replaced handlers')
plugin.setup(caller)
assert(#vim.api.nvim_get_autocmds({}) == #handlers, 'Repeated setup duplicated automatic handlers')
print('task-tools.nvim: setup input isolation, invalid configuration and registration lifetime passed')

local config = require('task_tools.config')
options.env.LIFECYCLE = 'changed'
assert(config.values.env.LIFECYCLE == 'value')
local before = vim.deepcopy(config.values)
assert(not pcall(plugin.setup, { watch_debounce = -1 }))
assert(vim.deep_equal(before, config.values))
local id =
  assert(plugin.run({ cmd = { vim.o.shell, '-c', 'sleep 0.05; printf stale' }, watch = true }, { open = false }))
plugin.dispose()
plugin.dispose()
local output = plugin.output(id)
vim.wait(150, function()
  return false
end)
assert(plugin.get(id).status == 'stopped')
assert(vim.deep_equal(output, plugin.output(id)), 'Disposed job delivered late output')
assert(#require('task_tools.watch').definitions() == 0)
assert(vim.fn.exists('#TaskToolsJobs') == 0 and vim.fn.exists('#TaskToolsWatch') == 0)
assert(vim.deep_equal(config.values, config.defaults))
plugin.setup(caller)
plugin.dispose()
